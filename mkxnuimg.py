#!/usr/bin/env python3
"""
Pack the redwood UEFI (with the hook that starts the XNU loader) and an optional payload
into an Android boot image for `fastboot boot`.

  redwood: kernel = gzip(BootShim + UEFI FD + ["XNUP" container]) + DTB, header v1
  lemonades probe: kernel = gzip(BootShim + UEFI FD), separate DTB, header v2

The boot shim copies the FD to its base and the payload to PAYLOAD_BASE.

The UEFI pieces are taken from a Mu-Silicium tree built here (Mu-Silicium/, see uefi/README.md)
or, when there is none, from prebuilt/uefi/.

usage: mkxnuimg.py [-p payload.bin] [-o out.img]

Another device (common/devices/<name>.conf, read by common/build.sh) sets these in the environment:
  UEFI_TARGET   Mu-Silicium device name (default redwood)    UEFI_FD, DTB   files to use instead
  FD_BASE, FD_SIZE, PAYLOAD_BASE                              addresses from its UEFI port's memory map
"""
import argparse, gzip, hashlib, json, os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
MU = os.path.join(HERE, 'Mu-Silicium')
PREBUILT = os.path.join(HERE, 'prebuilt', 'uefi')
def env_int(name, default):
    v = os.environ.get(name, '')
    return int(v, 0) if v else default
TARGET = os.environ.get('UEFI_TARGET') or 'redwood'
FD_BASE, FD_SIZE = env_int('FD_BASE', 0x9FD00000), env_int('FD_SIZE', 0x200000)
PAYLOAD_BASE, PAYLOAD_MAX = env_int('PAYLOAD_BASE', 0xF0000000), 0x04000000

ap = argparse.ArgumentParser()
ap.add_argument('-p', '--payload')
ap.add_argument('-o', '--output', default=os.path.join(HERE, 'xnu-redwood.img'))
ap.add_argument('--mode', default='RELEASE')
args = ap.parse_args()

fd_path = os.environ.get('UEFI_FD') or os.path.join(MU, f'Build/{TARGET}Pkg/{args.mode}_CLANGPDB/FV/SILICIUM_UEFI.fd')
if TARGET != 'redwood':
    # A different filename does not turn redwood's embedded addresses into a port.
    required = ('UEFI_FD', 'DTB', 'BOOT_SHIM', 'FD_BASE', 'FD_SIZE')
    missing = [key for key in required if not os.environ.get(key)]
    if missing:
        ap.error(f'{TARGET}: explicit device inputs required: {", ".join(missing)}; no redwood fallback')
    if args.payload:
        ap.error(f'{TARGET}: only the payload-free UEFI probe is supported; XNU memory layout is unvalidated')
    parts = {'shim': os.environ['BOOT_SHIM'], 'fd': fd_path, 'dtb': os.environ['DTB'],
             'ramdisk': os.path.join(PREBUILT, 'ramdisk'),
             'mkbootimg': os.path.join(PREBUILT, 'mkbootimg.py')}
    # Generated by tools/lemonades/build-shim.py; proves the shim was built with these constants.
    try:
        meta = json.loads(open(parts['shim'] + '.json').read())
        expected = {'target': TARGET, 'fd_base': FD_BASE, 'fd_size': FD_SIZE,
                    'payload_base': None,
                    'sha256': hashlib.sha256(open(parts['shim'], 'rb').read()).hexdigest()}
        if any(meta.get(k) != v for k, v in expected.items()):
            ap.error(f'{TARGET}: boot shim metadata does not match target, addresses or SHA-256')
    except (OSError, ValueError) as exc:
        ap.error(f'{TARGET}: missing/invalid boot shim metadata: {exc}')
elif os.path.isfile(fd_path) and os.path.isdir(os.path.join(MU, 'BootShim')):
    shim_dir = os.path.join(MU, 'BootShim')
    for f in ('BootShim.elf', 'BootShim.bin'):
        try: os.unlink(os.path.join(shim_dir, f))
        except FileNotFoundError: pass
    subprocess.check_call(['make', 'REQUIRES_KERNEL_HEADER=1', f'FD_BASE={FD_BASE:#x}', f'FD_SIZE={FD_SIZE:#x}',
                           f'CFLAGS=--target=aarch64-linux-gnu -DPAYLOAD_BASE={PAYLOAD_BASE:#x}'],
                          cwd=shim_dir, stdout=subprocess.DEVNULL)
    parts = {'shim': os.path.join(shim_dir, 'BootShim.bin'), 'fd': fd_path,
             'dtb': os.path.join(MU, f'Resources/DTBs/{TARGET}.dtb'), 'ramdisk': os.path.join(MU, 'Resources/ramdisk'),
             'mkbootimg': os.path.join(MU, 'Resources/Scripts/mkbootimg.py')}
else:
    if (FD_BASE, FD_SIZE, PAYLOAD_BASE) != (0x9FD00000, 0x200000, 0xF0000000):
        ap.error('prebuilt redwood BootShim has fixed addresses; rebuild it for changed addresses')
    parts = {'shim': os.path.join(PREBUILT, 'BootShim.bin'), 'fd': os.path.join(PREBUILT, 'SILICIUM_UEFI.fd'),
             'dtb': os.path.join(PREBUILT, 'redwood.dtb'), 'ramdisk': os.path.join(PREBUILT, 'ramdisk'),
             'mkbootimg': os.path.join(PREBUILT, 'mkbootimg.py')}
    if os.environ.get('UEFI_FD'): parts['fd'] = os.environ['UEFI_FD']
shim = open(parts['shim'], 'rb').read()
if TARGET != 'redwood' and (len(shim) < 64 or shim[56:60] != b'ARM\x64' or
        struct.unpack_from('<QQ', shim, 8) != (FD_BASE, FD_SIZE)):
    ap.error('boot shim ARM64 header does not match FD addresses')
fd = open(parts['fd'], 'rb').read()
if len(fd) != FD_SIZE:
    ap.error(f'UEFI FD has {len(fd):#x} bytes, expected {FD_SIZE:#x}')

blob = shim + fd
if args.payload:
    data = open(args.payload, 'rb').read()
    # the payload file is a complete "XNUP" container (see xnuloader/mkpayload.py)
    if (len(data) < 8 or data[:4] != b'XNUP' or len(data) > PAYLOAD_MAX - 0x100000 or
            struct.unpack_from('<I', data, 4)[0] != len(data) - 8):
        ap.error('bad or oversized payload (last 1 MiB is reserved for panic logs)')
    blob += data
    blob += b'\0' * (-len(blob) % 16)
    print(f'payload: {len(data)} bytes, bytesum={sum(data) & 0xffffffff:08x}')

if os.environ.get('DTB'): parts['dtb'] = os.environ['DTB']
dtb = open(parts['dtb'], 'rb').read()
if len(dtb) < 40 or dtb[:4] != b'\xd0\x0d\xfe\xed':
    ap.error('DTB is not a flattened device tree')
if struct.unpack_from('>I', dtb, 4)[0] != len(dtb):
    ap.error('DTB must be one complete tree, not a concatenated DTB/DTBO image')
compressed = gzip.compress(blob, 6, mtime=0)
if TARGET == 'lemonades':
    sys.path.insert(0, os.path.join(HERE, 'tools', 'lemonades'))
    from lineage import load_profile
    boot = load_profile()['boot_image']
    page = boot['pagesize']
    image_size = page + sum((size + page - 1) // page * page for size in
                           (len(compressed), os.path.getsize(parts['ramdisk']), len(dtb)))
    if image_size > boot['partition_size']:
        ap.error('lemonades image exceeds the LineageOS boot partition size')
    kernel_data = compressed
    boot_args = ['--header_version', str(boot['header_version']), '--base', hex(boot['base']),
                 '--pagesize', str(page), '--dtb', parts['dtb']]
else:
    kernel_data = compressed + dtb
    boot_args = ['--header_version', '1']
with tempfile.TemporaryDirectory(prefix='hackios-pack-') as tmp:
    kernel = os.path.join(tmp, 'kernel')
    open(kernel, 'wb').write(kernel_data)
    subprocess.check_call([sys.executable, parts['mkbootimg'], '--kernel', kernel, '--ramdisk', parts['ramdisk'],
                           *boot_args, '-o', args.output])
print(f'{args.output}: {os.path.getsize(args.output)} bytes (shim {len(shim)}, uncompressed {len(blob)})')
